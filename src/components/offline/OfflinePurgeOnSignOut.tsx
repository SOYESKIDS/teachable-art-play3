"use client";

import { useEffect } from "react";
import { purgeAll } from "@/lib/offline/offline-store";

/**
 * 로그인 화면 도착 시 오프라인 대기 기록 정리 — 사용자 지시 항목 4.
 *
 * ── 왜 로그인 화면인가 ─────────────────────────────────────────────
 *
 * 로그아웃은 route handler 가 처리하고 곧바로 redirect 한다. 그 경로에서는
 * 클라이언트 코드가 돌지 않으므로 IndexedDB 를 지울 기회가 없다.
 *
 * 반면 로그인 화면에 도착했다는 것은 **세션이 없다**는 뜻이다. 그래서 여기서
 * 전체를 지운다. 로그아웃 · 세션 만료 · 강제 로그아웃 어느 경로로 왔든 지난다.
 *
 * ── 전체를 지운다 ─────────────────────────────────────────────────
 *
 * 이 시점에는 어느 기관·사용자였는지 알 수 없다. scope 를 모르면 전부 지우는 것이
 * 맞다 — 다음 사용자가 이전 사용자의 기록을 읽거나 동기화하는 일을 막는 것이
 * 목적이기 때문이다. 레코드와 암호화 키를 함께 지운다.
 *
 * ── 화면에 아무것도 그리지 않는다 ──────────────────────────────────
 */
export function OfflinePurgeOnSignOut() {
  useEffect(() => {
    void purgeAll();
  }, []);

  return null;
}
